const updateCountdown = () => {
  const target = new Date(config.date).getTime();
  const distance = Math.max(target - Date.now(), 0);

  const days = Math.floor(distance / 86400000);
  const hours = Math.floor((distance % 86400000) / 3600000);
  const minutes = Math.floor((distance % 3600000) / 60000);
  const seconds = Math.floor((distance % 60000) / 1000);

  setText("days", String(days).padStart(3, "0"));
  setText("hours", String(hours).padStart(2, "0"));
  setText("minutes", String(minutes).padStart(2, "0"));
  setText("seconds", String(seconds).padStart(2, "0"));
};

const setupEntry = () => {
  const entry = document.getElementById("demoEntry");
  const enterButton = document.getElementById("enterExperience");

  document.body.classList.add("entry-open");

  enterButton.addEventListener("click", () => {
    entry.classList.add("hidden");
    document.body.classList.remove("entry-open");
  });
};

const setupNavigation = () => {
  const menuButton = document.getElementById("demoMenuButton");
  const nav = document.getElementById("demoNav");

  menuButton.addEventListener("click", () => {
    nav.classList.toggle("open");
  });

  nav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      nav.classList.remove("open");
    });
  });
};

const setupReveal = () => {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) {
          return;
        }

        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      });
    },
    {
      threshold: 0.1,
    },
  );

  document.querySelectorAll(".reveal").forEach((element) => {
    observer.observe(element);
  });
};

const setupModals = () => {
  const rsvpModal = document.getElementById("rsvpModal");
  const galleryModal = document.getElementById("galleryModal");

  document.getElementById("openRsvpForm").addEventListener("click", () => {
    rsvpModal.showModal();
  });

  document.getElementById("closeRsvpModal").addEventListener("click", () => {
    rsvpModal.close();
  });

  document.getElementById("closeGalleryModal").addEventListener("click", () => {
    galleryModal.close();
  });

  document.querySelectorAll(".gallery-item").forEach((item) => {
    item.addEventListener("click", () => {
      galleryModal.showModal();
    });
  });

  document.getElementById("rsvpForm").addEventListener("submit", (event) => {
    event.preventDefault();

    setText(
      "formStatus",
      "Confirmación registrada en esta demo. En producción se enviará al panel del evento.",
    );
  });
};

const setupMusic = () => {
  const control = document.getElementById("musicControl");
  const audio = document.getElementById("experienceAudio");

  control.addEventListener("click", async () => {
    if (!audio.src) {
      control.querySelector(".music-label").textContent =
        "Música de demostración";
      return;
    }

    if (audio.paused) {
      await audio.play();
      control.classList.add("playing");
      control.querySelector(".music-label").textContent = "Pausar";
    } else {
      audio.pause();
      control.classList.remove("playing");
      control.querySelector(".music-label").textContent = "Música";
    }
  });
};

window.addEventListener("load", () => {
  buildDemo();
  setupEntry();
  setupNavigation();
  setupReveal();
  setupModals();
  setupMusic();
  updateCountdown();

  setInterval(updateCountdown, 1000);

  window.setTimeout(() => {
    document.getElementById("demoLoader").classList.add("hidden");
  }, 450);
});
